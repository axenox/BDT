            if (!$facade instanceof UI5Facade) {
                throw new RuntimeException('Cannot initialize the UI5 facade: got "' . get_class($facade) . '" instead of ' . UI5Facade::class . '.');
            }
            $this->facade = $facade;
        }
        return $this->facade;
    }

