    /**
     * Takes a screenshot of the current browser state through the callback wired by the context.
     *
     * WHY the reason is written to the logbook and not only to ErrorManager: the report shows the
     * logbook right next to the failed step, while an ErrorManager entry lives somewhere else
     * entirely. Without this line a missing picture is indistinguishable from a picture that was
     * never requested - which is how a broken screenshot path stayed invisible for whole runs.
     *
     * WHY it still swallows the throwable: it is called from failure handling, and a screenshot that
     * cannot be stored must never replace the original test failure.
     *
     * @param LogBookInterface|null $logbook Logbook of the failing step, if the caller has one
     * @return void
     */
    public function captureScreenshot(?LogBookInterface $logbook = null): void
    {
        if ($this->screenshotFn === null) {
            $logbook?->addLine('**WARNING:** No screenshot stored - no screenshot callback is wired into the browser.');
            return;
        }

        try {
            ($this->screenshotFn)();
        } catch (Throwable $e) {
            $logbook?->addLine('**WARNING:** No screenshot stored: ' . $e->getMessage());
            ErrorManager::getInstance()->logException($e, $this->getWorkbench());
        }
    }

    /**
     * Logs out the current browser session by calling the ExFace Logout action via
     * synchronous XHR from within the browser. This ensures the HttpOnly session
     * cookie is sent automatically without any page navigation.
     */
    public function logOutIfAlreadyLoggedIn($baseUrl): void
    {
        $webapp = $this->findAppFromUrl($this->getSession()->getCurrentUrl());
        $apiUrl = rtrim($baseUrl, '/') . '/api/ui5';
        $this->getSession()->evaluateScript(<<<JS
        (function() {
            var xhr = new XMLHttpRequest();
            xhr.open('POST', '$apiUrl', false);
            xhr.setRequestHeader('Content-Type', 'application/x-www-form-urlencoded');
            xhr.setRequestHeader('X-Requested-With', 'XMLHttpRequest');
            xhr.send('action=exface.Core.Logout&resource=$webapp&webapp=$webapp');
        })();
    JS
        );
    }

    public function findAppFromUrl(string $currentUrl): string
    {
        $pagePath = basename(parse_url($currentUrl, PHP_URL_PATH));
        return preg_replace('/\.html$/', '', $pagePath);
    }

    /**
     * Attempts to close any SAP UI5 error dialog currently blocking the DOM.
     *
     * Called from the abstract node layer immediately after the screenshot is captured,
     * so the dialog is still visible in the screenshot but no longer blocks subsequent
     * back-navigation or teardown interactions.
     *
     * Uses SAP UI5's own control API (sap.ui.getCore().byId().close()) rather than
     * native .click(), because UI5 buttons bypass the browser's native click handler
     * and route events through their own delegation system.
     *
     * @return bool True if a dialog was found and dismissed, false if none was present.
     */
    public function dismissErrorDialogIfPresent(): bool
    {
        $dismissed = $this->getSession()->evaluateScript(<<<'JS'
(function () {
    // Target the SAP UI5 error dialog — class 'sapMDialogError' is always present
    // on sap.m.Dialog instances rendered with type MessageType.Error.
    var dialog = document.querySelector('.sapMDialogError');
    if (!dialog) return false;

    var controlId = dialog.getAttribute('id');
    if (controlId && typeof sap !== 'undefined') {
        var control = sap.ui.getCore().byId(controlId);
        if (control && typeof control.close === 'function') {
            control.close();
            return true;
        }
    }

    // Fallback: trigger the designated end-button directly for custom dialog layouts
    // where the control API may not be available (e.g. unit-test stubs).
    var closeBtn = dialog.querySelector('button.sapMDialogEndButton');
    if (!closeBtn) {
        var buttons = dialog.querySelectorAll('button');
        for (var i = 0; i < buttons.length; i++) {
            var txt = (buttons[i].innerText || buttons[i].textContent || '').trim().toLowerCase();
            if (txt === 'close' || txt === 'schließen' || txt === 'schliessen') {
                closeBtn = buttons[i];
                break;
            }
        }
    }
    if (closeBtn) { closeBtn.click(); return true; }

    return false;
})();
JS
        );

        return (bool)$dismissed;
    }

    /**
     * Registers the Chrome recovery callback from UI5BrowserContext.
     * Nodes deep in the tree (e.g. UI5ContainerNode) need to trigger a Chrome restart
     * but have no direct reference to the context. This callback bridges that gap,
     * following the same pattern as setNavigator() and setScreenshotFn().
     * The callable receives the target page alias to navigate to after recovery.
     */
    public function setChromeRecoveryFn(callable $fn): void
    {
        $this->chromeRecoveryFn = $fn;
    }

    /**
     * Invokes the Chrome recovery callback registered via setChromeRecoveryFn().
     * Called by UI5ContainerNode when a ChromeHangException is caught mid-iteration.
     * The actual restart, re-login and navigation are performed by UI5BrowserContext::recoverChrome().
     *
     * @param string $targetPageAlias The container page to navigate to after recovery,
     *                                so the retry can find child DOM elements again.
     */
    public function recoverChrome(string $targetPageAlias): void
    {
        if ($this->chromeRecoveryFn === null) {
            throw new \RuntimeException('Chrome recovery callback not configured. Call setChromeRecoveryFn() first.');
        }
        ($this->chromeRecoveryFn)($targetPageAlias);
    }
