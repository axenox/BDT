    /**
     * Returns the id of the DOM element / UI5 control the facade renders for the given widget.
     *
     * WHY the id is computed instead of read from a facade element: asking the facade for an element
     * builds the whole thing - init() runs, controller dependencies get registered, external modules
     * are pulled in. Outside a real rendering request there is no controller, so elements that touch
     * it while initialising (UI5Markdown registers its editor there) abort with
     * "No controller was initialized for page ...". A test only needs the id, not a renderable
     * element, so it must not pay that price.
     *
     * WHY it is safe to rebuild the scheme here: it consists of exactly two steps, both taken from
     * the facade itself - the page UID without its leading character (UI5AbstractElement::getId())
     * and cleanId(), which replaces the characters the facade config declares forbidden with "_".
     * The dot matters most: UiPage uses it as its id space separator, so a widget id like
     * "..._DataButton05.VerortungId" is rendered as "..._DataButton05_VerortungId". Reading the
     * character list from the facade config keeps this in sync if the facade ever changes it.
     *
     * @param WidgetInterface $widget
     * @return string
     */
    public function getElementIdFromWidget(WidgetInterface $widget) : string
    {
        $forbiddenChars = $this->getFacade()
            ->getConfig()
            ->getOption('WIDGET.ALL.FORBIDDEN_CHARS_IN_ELEMENT_ID')
            ->toArray();
        return substr($widget->getPage()->getUid(), 1)
            . '__'
            . str_replace($forbiddenChars, '_', $widget->getId());
    }

    /**
     * Gets the UI5Facade instance used for UI5-specific operations
     * Lazy-loads the facade if not already instantiated
     *
     * WHY the explicit instance check: FacadeFactory::createFromString() is declared to return the
     * generic FacadeInterface, so assigning its result to a UI5Facade-typed property is not provable
     * for static analysis. Narrowing here documents the expectation and turns a wrong selector into a
     * named error instead of a type error deep inside the first element call.
     *
     * @return UI5Facade UI5 facade instance
     */
    public function getFacade(): UI5Facade
